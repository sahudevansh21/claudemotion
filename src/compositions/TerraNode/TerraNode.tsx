import { Audio } from "@remotion/media";
import { AbsoluteFill, Sequence, staticFile } from "remotion";
import { ApproveScene } from "./scenes/ApproveScene";
import { FieldScene } from "./scenes/FieldScene";
import { LeafScene } from "./scenes/LeafScene";
import { NetworkScene } from "./scenes/NetworkScene";
import { NodeScene } from "./scenes/NodeScene";
import { RowsScene } from "./scenes/RowsScene";
import { SkyScene } from "./scenes/SkyScene";
import { TabletScene } from "./scenes/TabletScene";
import { scene } from "./timeline";

/**
 * TerraNode — 20 s brand film, 1920x1080 @ 30 fps.
 *
 * Mirrors the reference's cinematic structure: golden-hour fields and
 * handheld camera, the product seen in use out in the field, then a tilt up
 * into a clean sky where the wordmark types on.
 * Three beats: (1) the promise (shots 1–2), (2) the product at work
 * (shots 3–7), (3) the brand (shot 8). Every cut and cue comes from
 * timeline.json, which also drives the generated audio.
 */
const SCENES: { id: string; Component: React.FC }[] = [
  { id: "field", Component: FieldScene },
  { id: "rows", Component: RowsScene },
  { id: "node", Component: NodeScene },
  { id: "tablet", Component: TabletScene },
  { id: "leaf", Component: LeafScene },
  { id: "approve", Component: ApproveScene },
  { id: "network", Component: NetworkScene },
  { id: "sky", Component: SkyScene },
];

export const TerraNode: React.FC = () => {
  return (
    <AbsoluteFill style={{ backgroundColor: "#000" }}>
      {SCENES.map(({ id, Component }) => {
        const s = scene(id);
        return (
          <Sequence
            key={id}
            name={id}
            from={s.start}
            durationInFrames={s.duration}
            premountFor={30}
          >
            <Component />
          </Sequence>
        );
      })}
      {/* Generated by scripts/terranode/generate_audio.py from timeline.json */}
      <Audio src={staticFile("terranode/audio/mix.wav")} />
    </AbsoluteFill>
  );
};
