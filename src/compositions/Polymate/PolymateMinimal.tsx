import { Audio } from "@remotion/media";
import { AbsoluteFill, Sequence, staticFile } from "remotion";
import { Stage } from "../../components/Stage";
import { EndShot, MarbleShot, MarkShot, mshot, SkyShot, TradeShot } from "./minimal/Shots";

/**
 * POLYMATE — 10 s minimal product film, 3840x2160 @ 60 fps (600 frames).
 * Motion grammar from the supplied reference (calm cinematic plates, tiny
 * wide-tracked mono captions that decode in behind a block cursor, a white
 * highlight box on the key words, glitch scramble-out, small logo end card);
 * look from the Polymate X banner (golden-hour sky, columns, crimson banner,
 * marble, gold laurel). Timing: minimal/minimal.json.
 */
const SHOTS = [
  { id: "sky", el: <SkyShot /> },
  { id: "marble", el: <MarbleShot /> },
  { id: "trade", el: <TradeShot /> },
  { id: "mark", el: <MarkShot /> },
  { id: "end", el: <EndShot /> },
];

export const PolymateMinimal: React.FC = () => (
  <AbsoluteFill style={{ background: "#000" }}>
    {SHOTS.map(({ id, el }) => {
      const s = mshot(id);
      return (
        <Sequence key={id} name={id} from={s.start} durationInFrames={s.duration} premountFor={60}>
          <Stage>{el}</Stage>
        </Sequence>
      );
    })}
    {/* Generated by scripts/polymate/generate_minimal_audio.py from minimal/minimal.json */}
    <Audio src={staticFile("polymate/minimal-audio/mix.wav")} />
  </AbsoluteFill>
);
