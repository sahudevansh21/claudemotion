import { Audio } from "@remotion/media";
import { AbsoluteFill, Sequence, staticFile } from "remotion";
import { CL } from "./brand";
import { ClosingScene } from "./scenes/ClosingScene";
import { DashboardScene } from "./scenes/DashboardScene";
import { ProblemScene } from "./scenes/ProblemScene";
import { SignalScene } from "./scenes/SignalScene";
import { WorkflowScene } from "./scenes/WorkflowScene";
import { scene } from "./timeline";

/**
 * COLLATERA — 30 s brand film, 1920x1080 @ 60 fps (1,800 frames).
 *
 * Visual identity from the supplied logo, banner and website; motion grammar
 * from the supplied demo reel (pixel type-on cards, sideways pushes, UI
 * zooms with a cursor, stacking feeds). Scene timing follows the brief and
 * comes from timeline.json, which also drives the generated audio.
 */
const SCENES: { id: string; Component: React.FC }[] = [
  { id: "signal", Component: SignalScene },
  { id: "problem", Component: ProblemScene },
  { id: "dashboard", Component: DashboardScene },
  { id: "workflow", Component: WorkflowScene },
  { id: "closing", Component: ClosingScene },
];

export const Collatera: React.FC = () => {
  return (
    <AbsoluteFill style={{ backgroundColor: CL.evergreen }}>
      {SCENES.map(({ id, Component }) => {
        const s = scene(id);
        return (
          <Sequence
            key={id}
            name={id}
            from={s.start}
            durationInFrames={s.duration}
            premountFor={60}
          >
            <Component />
          </Sequence>
        );
      })}
      {/* Generated by scripts/collatera/generate_audio.py from timeline.json */}
      <Audio src={staticFile("collatera/audio/mix.wav")} />
    </AbsoluteFill>
  );
};
