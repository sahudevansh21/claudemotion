import { Audio } from "@remotion/media";
import { AbsoluteFill, Sequence, staticFile } from "remotion";
import { Stage } from "../../components/Stage";
import { NS } from "./brand";
import live from "./live.json";
import { CloseShot, LineupShot, LiveEndShot, NetworkShot, ShouldShot } from "./scenes/Live";
import { makeTimeline } from "./timeline";

const { shot } = makeTimeline(live);

/**
 * NIGHTSHIFT — "Now live on" announcement, 15 s, 1920x1080 @ 30 fps (450
 * frames). Same visual language as the teaser: night city + giant type, the
 * engine core wiring up to each rail (Algorand, Harmonic, Sentora, Morpho),
 * a "NOW LIVE ON" line-up on the beat drop, end card. Timing and audio come
 * from live.json.
 */
const SHOTS: { id: string; el: React.ReactNode }[] = [
  { id: "close", el: <CloseShot /> },
  { id: "should", el: <ShouldShot /> },
  { id: "network", el: <NetworkShot /> },
  { id: "lineup", el: <LineupShot /> },
  { id: "end", el: <LiveEndShot /> },
];

export const NightshiftLive: React.FC = () => {
  return (
    <AbsoluteFill style={{ backgroundColor: NS.bg }}>
      {SHOTS.map(({ id, el }) => {
        const s = shot(id);
        return (
          <Sequence key={id} name={id} from={s.start} durationInFrames={s.duration} premountFor={30}>
            <Stage>{el}</Stage>
          </Sequence>
        );
      })}
      {/* Generated by `scripts/nightshift/generate_audio.py live.json public/nightshift/live-audio` */}
      <Audio src={staticFile("nightshift/live-audio/mix.wav")} />
    </AbsoluteFill>
  );
};
