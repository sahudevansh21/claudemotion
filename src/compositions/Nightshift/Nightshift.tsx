import { Audio } from "@remotion/media";
import { AbsoluteFill, Sequence, staticFile } from "remotion";
import { Stage } from "../../components/Stage";
import { NS } from "./brand";
import { BuildShot, DeskShot, LogoShot, PromptShot } from "./scenes/Act1";
import { ProductsShot, StatementCard, StatusShot, WallShot, ZoomShot } from "./scenes/Act2";
import { CityShot, EndShot } from "./scenes/Act3";
import { shot } from "./timeline";

/**
 * NIGHTSHIFT — 30 s motion-graphics teaser, 1920x1080 @ 30 fps (900 frames).
 *
 * Structure and motion grammar follow the supplied reference teaser (logo
 * type-on, multiplayer cursors on a node canvas, prompt box, light statement
 * cards, zoom-out wall, big node close-up, giant stacked type over city
 * inserts, chip tags, end card). All copy and sample values come from the
 * supplied Nightshift site screenshots. Every cut lands on a beat (120 BPM).
 */
const SHOTS: { id: string; el: React.ReactNode }[] = [
  { id: "logo", el: <LogoShot /> },
  { id: "desk", el: <DeskShot /> },
  { id: "prompt", el: <PromptShot /> },
  { id: "build", el: <BuildShot /> },
  { id: "card1", el: <StatementCard id="card1" lines={["IT PRICES", "AFTER THE BELL"]} /> },
  { id: "wall", el: <WallShot /> },
  { id: "status", el: <StatusShot /> },
  { id: "products", el: <ProductsShot /> },
  { id: "card2", el: <StatementCard id="card2" lines={["WALL STREET SLEEPS.", "THE ENGINE DOESN'T."]} /> },
  { id: "zoom", el: <ZoomShot /> },
  { id: "city", el: <CityShot /> },
  { id: "end", el: <EndShot /> },
];

export const Nightshift: React.FC = () => {
  return (
    <AbsoluteFill style={{ backgroundColor: NS.bg }}>
      {SHOTS.map(({ id, el }) => {
        const s = shot(id);
        return (
          <Sequence key={id} name={id} from={s.start} durationInFrames={s.duration} premountFor={30}>
            <Stage>{el}</Stage>
          </Sequence>
        );
      })}
      {/* Generated by scripts/nightshift/generate_audio.py from timeline.json */}
      <Audio src={staticFile("nightshift/audio/mix.wav")} />
    </AbsoluteFill>
  );
};
